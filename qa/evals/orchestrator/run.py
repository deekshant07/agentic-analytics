"""
evals/orchestrator/run.py — Query Understanding gold-dataset eval.

Tests the orchestrator layer in isolation: does the LLM correctly parse a natural-language
question into the right QueryObject slots (analysis_type, metric_id, filters, time_range)?

Two-phase design (LLM calls once, score for free anytime):

  Phase 1 — generate (1 LLM call per query):
      python -m qa.evals.orchestrator.run --save-outputs /tmp/run.json

  Phase 2 — score (deterministic, free):
      python -m qa.evals.orchestrator.run --from-outputs /tmp/run.json

  Rerun only failures from a previous report:
      python -m qa.evals.orchestrator.run --rerun-failures qa/results/orchestrator/openai/20260525.json

  Switch provider without touching .env:
      python -m qa.evals.orchestrator.run --save-outputs /tmp/run.json --provider groq
      python -m qa.evals.orchestrator.run --save-outputs /tmp/run.json --provider gemini

Results are auto-saved to:  qa/results/orchestrator/{provider}/YYYYMMDD_HHMMSS.json

Gold labels in gold.yaml are human-defined — never generated by the model under test.
Scoring is purely deterministic: string match, dict comparison, numeric tolerance.
No LLM judge.

Scores 5 dimensions per query:
  1. Intent     (40%) — analysis_type extracted correctly
  2. Metric     (25%) — metric_id extracted correctly
  3. Filters    (20%) — required filters present with correct values
  4. Time-range (10%) — time window / date range extracted correctly
  5. Ambiguity   (5%) — clarify returned for genuinely ambiguous queries
"""

